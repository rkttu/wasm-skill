"""Build the Python-entry compact skill using stdlib only; no runtime downloads."""
import argparse
import hashlib
import json
from pathlib import Path
import shutil
import urllib.request
import zipfile
import base64

ROOT = Path(__file__).resolve().parent.parent
LIMIT = 50_000_000  # Conservative decimal 50 MB, including expanded payload.
SKILL = "c-wasm-portable-wcc"
ALLOWED = {".md", ".txt", ".json", ".py", ".mjs"}


def sha(data):
    return hashlib.sha256(data).hexdigest()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--fetch", action="store_true", help="Download the pinned upstream assets for development packaging")
    parser.add_argument("--data-only", action="store_true", help="Prepare compiler-data.mjs without packaging")
    args = parser.parse_args()
    manifest = json.loads((ROOT / "wcc-toolchain.json").read_text(encoding="utf-8"))
    vendored = ROOT / "vendor" / "wcc" / "wccfiles.zip"
    cached = vendored if vendored.is_file() else ROOT / ".cache" / "wcc-research" / "wccfiles.zip"
    if args.fetch and not cached.exists():
        cached.parent.mkdir(parents=True, exist_ok=True)
        with urllib.request.urlopen(manifest["archive_url"], timeout=60) as response:
            data = response.read(manifest["archive_bytes"] + 1)
        if len(data) != manifest["archive_bytes"] or sha(data) != manifest["archive_sha256"]:
            raise ValueError("Upstream asset changed; review and pin a new manifest before packaging.")
        cached.write_bytes(data)
    data = cached.read_bytes()
    if len(data) != manifest["archive_bytes"] or sha(data) != manifest["archive_sha256"]:
        raise ValueError("Cached wcc assets size/SHA-256 mismatch.")
    with zipfile.ZipFile(cached) as archive:
        compiler = archive.read(manifest["compiler_path"])
        headers = {name.removeprefix("usr/include/"): archive.read(name).decode("utf-8")
                   for name in sorted(archive.namelist())
                   if name.startswith("usr/include/") and not name.endswith("/")}
    if len(compiler) != manifest["compiler_bytes"] or sha(compiler) != manifest["compiler_sha256"]:
        raise ValueError("Compiler integrity check failed.")
    if not headers or any(".." in Path(name).parts for name in headers):
        raise ValueError("Invalid embedded include resources.")
    backend = ROOT / "src" / "portable"
    backend.mkdir(parents=True, exist_ok=True)
    embedded = (
        "// Generated by tools/package-portable.py. MIT-licensed wcc compiler and headers.\n"
        "// Wasm bytes are embedded as base64 for a self-contained JavaScript module.\n"
        f"export const COMPILER_BASE64 = {json.dumps(base64.b64encode(compiler).decode('ascii'))};\n"
        f"export const COMPILER_SHA256 = {json.dumps(manifest['compiler_sha256'])};\n"
        f"export const HEADERS = Object.freeze({json.dumps(headers, ensure_ascii=True, sort_keys=True)});\n"
        f"export const PROVENANCE = Object.freeze({json.dumps(manifest, sort_keys=True)});\n"
    )
    (backend / "compiler-data.mjs").write_text(embedded, encoding="utf-8", newline="\n")
    if args.data_only:
        print(json.dumps({"compiler_bytes": len(compiler), "headers": len(headers)}))
        return
    target = ROOT / "skills" / SKILL
    target.mkdir(parents=True, exist_ok=True)
    for source, destination in [("LICENSE", "LICENSE.txt"), ("NOTICE", "NOTICE.txt")]:
        shutil.copyfile(ROOT / source, target / destination)
    for source in sorted((ROOT / "portable-template").rglob("*")):
        if source.is_file():
            dest = target / source.relative_to(ROOT / "portable-template")
            dest.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(source, dest)
    scripts = target / "scripts"
    scripts.mkdir(exist_ok=True)
    for source in sorted(backend.iterdir()):
        if source.suffix in {".py", ".mjs"}:
            content = source.read_text(encoding="utf-8").replace("'../wasm.mjs'", "'./wasm.mjs'").replace("'../verify.mjs'", "'./verify.mjs'")
            (scripts / source.name).write_text(content, encoding="utf-8", newline="\n")
    for name in ["wasm.mjs", "verify.mjs"]:
        shutil.copyfile(ROOT / "src" / name, scripts / name)
    (target / "examples").mkdir(exist_ok=True)
    shutil.copyfile(ROOT / "template" / "examples" / "module.c", target / "examples" / "module.c.txt")
    shutil.copyfile(ROOT / "template" / "examples" / "module.spec.json", target / "examples" / "module.spec.json")
    shutil.copyfile(ROOT / "template" / "references" / "contract.md", target / "references" / "contract.md")
    (target / "references" / "provenance.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    files = sorted(p for p in target.rglob("*") if p.is_file())
    expanded = sum(p.stat().st_size for p in files)
    if len(files) > 350 or expanded >= LIMIT:
        raise ValueError("Bundle resource count/expanded size exceeds limits.")
    for file in files:
        relative = file.relative_to(target)
        if file.is_symlink() or file.suffix not in ALLOWED or len(relative.parts) > 3 or file.stat().st_size > 25_000_000:
            raise ValueError(f"Unexpected resource type/depth/size: {relative}")
    if len((target / "SKILL.md").read_text(encoding="utf-8")) >= 20_000:
        raise ValueError("SKILL.md exceeds instruction character budget.")
    dist = ROOT / "dist"
    dist.mkdir(exist_ok=True)
    output = dist / f"{SKILL}.zip"
    with zipfile.ZipFile(output.with_suffix(".zip.tmp"), "w", compression=zipfile.ZIP_DEFLATED, compresslevel=9) as archive:
        for file in files:
            info = zipfile.ZipInfo(file.relative_to(target).as_posix(), date_time=(1980, 1, 1, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o100644 << 16
            archive.writestr(info, file.read_bytes(), compresslevel=9)
    output.with_suffix(".zip.tmp").replace(output)
    payload = output.read_bytes()
    if len(payload) >= LIMIT:
        raise ValueError("Compressed bundle exceeds 50 MB.")
    with zipfile.ZipFile(output) as archive:
        if archive.testzip() is not None or "SKILL.md" not in archive.namelist():
            raise ValueError("ZIP integrity/root instructions check failed.")
    (dist / f"SHA256SUMS-{SKILL}").write_text(f"{sha(payload)}  {output.name}\n", encoding="ascii")
    print(json.dumps({"skill": str(target), "zip": str(output), "bytes": len(payload), "expanded_bytes": expanded, "files": len(files), "sha256": sha(payload)}))


if __name__ == "__main__":
    main()
